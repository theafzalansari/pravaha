export const getZoneHexColor = (risk: string) => {
  const r = (risk || "").toUpperCase();
  if (r === "CRITICAL") return "#c94b3d";
  if (r === "HIGH") return "#d87535";
  if (r === "WARNING" || r === "RISING") return "#c79528";
  return "#3d9560";
};

